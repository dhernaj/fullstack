-- Esquema para bases nuevas; Hibernate valida las entidades sin recrear tablas.
CREATE TABLE cursos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(7) NOT NULL,
    nombre VARCHAR(100) NOT NULL,
    creditos INTEGER NOT NULL,
    docente VARCHAR(80) NOT NULL,
    cupos INTEGER NOT NULL,
    activo BOOLEAN NOT NULL,
    version BIGINT,
    CONSTRAINT uk_cursos_codigo UNIQUE (codigo)
);

CREATE TABLE estudiantes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(10) NOT NULL,
    nombres VARCHAR(60) NOT NULL,
    apellidos VARCHAR(60) NOT NULL,
    email VARCHAR(120) NOT NULL,
    CONSTRAINT uk_estudiantes_codigo UNIQUE (codigo),
    CONSTRAINT uk_estudiantes_email UNIQUE (email)
);

CREATE TABLE matriculas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estudiante_id BIGINT NOT NULL,
    curso_id BIGINT NOT NULL,
    fecha DATE NOT NULL,
    estado VARCHAR(10) NOT NULL,
    CONSTRAINT uk_matriculas_estudiante_curso UNIQUE (estudiante_id, curso_id),
    CONSTRAINT fk_matriculas_estudiante FOREIGN KEY (estudiante_id) REFERENCES estudiantes(id),
    CONSTRAINT fk_matriculas_curso FOREIGN KEY (curso_id) REFERENCES cursos(id),
    CONSTRAINT ck_matriculas_estado CHECK (estado IN ('ACTIVA', 'RETIRADA'))
);
CREATE INDEX ix_matriculas_curso ON matriculas(curso_id);

CREATE TABLE usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL,
    password VARCHAR(100) NOT NULL,
    rol VARCHAR(15) NOT NULL,
    estudiante_id BIGINT,
    CONSTRAINT uk_usuarios_username UNIQUE (username),
    CONSTRAINT uk_usuarios_estudiante UNIQUE (estudiante_id),
    CONSTRAINT fk_usuarios_estudiante FOREIGN KEY (estudiante_id) REFERENCES estudiantes(id),
    CONSTRAINT ck_usuarios_rol CHECK (rol IN ('ADMIN', 'DOCENTE', 'ESTUDIANTE'))
);
